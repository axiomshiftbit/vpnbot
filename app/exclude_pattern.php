<?php

/**
 * Регулярка «домен входит в список исключений».
 *
 * preg_quote по КАЖДОМУ элементу: subzone — это домен, где «.» матчила любой
 * символ, а один спецсимвол (скобка, «+») ломал регулярку целиком, и тогда
 * preg_match молча возвращал false — исключения переставали работать вообще.
 *
 * Делимитер обязателен вторым аргументом: без него preg_quote не экранирует
 * «~», то есть ровно тот символ, которым огорожен паттерн.
 */
function excludePattern(array $exclude): string
{
    return '~' . implode('|', array_map(fn ($e) => preg_quote((string) $e, '~'), $exclude)) . '~';
}
