<b>Достаточно одного совпадения</b>
Две записи <code>domain:example.com</code> и <code>full:login.example.net</code> в одном списке выбирают первый ИЛИ второй сайт. Они не требуют, чтобы соединение совпало с обеими сразу.

<b>Порядок действий задаётся профилем</b>
Для правил выбора маршрута используется первое подходящее действие. Положение записи на странице бота и порядок добавления не задают её приоритет.

В стандартных профилях блокировка идёт раньше маршрутизации через VPN. На сервере правила block также проверяются раньше WARP.

<b>Пример пересечения</b>
В domains: <code>domain:example.com</code>.
В block: <code>full:ads.example.com</code>.
Результат в стандартном профиле:
• example.com и www.example.com — через VPN;
• ads.example.com — заблокирован.
Точность full: сама по себе не даёт приоритет: его обеспечивает порядок действий.

Если в block стоит <code>domain:example.com</code>, добавление <code>full:login.example.com</code> в domains не создаст исключение из блокировки. Нужно изменить само широкое правило или порядок/условия в своём шаблоне.

<b>Когда вступают в силу изменения</b>
• block/WARP пересобираются на сервере Xray при изменении списка; применение может кратко прервать соединения.
• Клиентские списки требуют актуального профиля: обновите подписку, выберите/примените обновлённый профиль, при необходимости переподключитесь.
• Одна ссылка <code>vless://</code> содержит параметры подключения, но не эти списки маршрутизации.

Для Mihomo нужен режим правил (rule). Режимы Global/Direct меняют обычное применение клиентских правил. Пользовательский шаблон также может изменить приоритеты, выход по умолчанию или вовсе не использовать какой-то список.

<b>Правила привязаны к настройкам бота</b>
Клиентские списки используются профилями, в которые они включены; серверные — поступающими на Xray соединениями. Эти списки не являются персональной настройкой одного выбранного пользователя.

Сервер не обрабатывает трафик, который клиент отправил напрямую. Клиентская маршрутизация и серверная блокировка должны рассматриваться вместе.
