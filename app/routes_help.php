<b>Примеры для Mihomo</b>
<code>proxy:domain:1d:https://example.org/domains.yaml</code>
Файл с доменными шаблонами.

<code>direct:ipcidr:1d:https://example.org/networks.txt</code>
Текстовый файл с сетями.

<code>block:classical:1h:https://example.org/ads.yml</code>
YAML со списком полных правил.

<b>Ограничение MRS</b>
MRS поддерживает только domain или ipcidr. Запись <code>proxy:1d:https://example.org/list.mrs</code> неверна: без явного типа получится classical. Правильно:
<code>proxy:domain:1d:https://example.org/list.mrs</code>
Регулярные выражения в полных правилах Mihomo требуют другого подходящего формата, например classical YAML.

<b>Формат важнее расширения</b>
Переименование .srs в .mrs не преобразует файл. Формат строк внутри источника может отличаться от ручного ввода domain:/full:/regexp: в боте. Следуйте описанию автора списка.

Используйте прямую ссылку на файл, а не страницу просмотра GitHub. Проверяйте, что по ней приходит список, а не HTML ошибки. Для Mihomo предпочтительнее MRS/YAML: некорректный TXT может быть принят как пустой набор.

Выбирайте источник для вашего клиентского ядра: один формат не становится автоматически пригодным для всех клиентов. Внешние .dat для серверного Xray подключаются отдельно, в меню dat.
