<b>Для Mihomo</b>
Поддерживаются <code>.yaml</code>, <code>.yml</code>, <code>.txt</code>, <code>.mrs</code>. Дополнительно укажите, что находится внутри:
• <code>domain</code> — доменные шаблоны;
• <code>ipcidr</code> — IP-адреса/подсети;
• <code>classical</code> — полные правила Mihomo, например DOMAIN-SUFFIX или IP-CIDR.
