.dat — база категорий доменов или IP для Xray. Она хранится на VPN-сервере. Файл подключают в <b>routes → dat</b>, а действие выбирают записью в <b>block</b> или <b>WARP</b>.

<b>Шаг 1. Добавить источник</b>
Формат:
<code>имя.dat:https://прямая-ссылка-на-файл</code>
Примеры схемы записи:
<code>sites.dat:https://example.org/geosite.dat
networks.dat:https://example.org/geoip.dat</code>
Замените ссылки example.org настоящими HTTPS-ссылками. Первый файл должен иметь формат GeoSite, второй — GeoIP. Это не переименованный TXT, YAML или SRS.

<b>Шаг 2. Убедиться, что источник включён и загружен</b>
В меню dat под расписанием показаны файлы: размер, дата загрузки и причина последнего отказа, если он был. Отметка <b>sha256 ✅</b> значит, что сумма файла сверена с опубликованной рядом (<code>ссылка.sha256sum</code>); при несовпадении файл не заменяется. Ответ, не похожий на .dat (страница ошибки, архив), тоже отклоняется, прежний файл остаётся.

<b>Автообновление</b>
Кнопка <b>автообновление</b>: готовые интервалы от 30 минут до 30 дней или <b>свой интервал</b> — число и единица, например <code>90m</code>, <code>36h</code>, <code>10d</code> (от 15 минут до 90 дней). Для интервала от суток можно выбрать час запуска: обновление будет приходиться на этот час по часовому поясу бота. При неудаче бот сообщает администраторам и повторяет попытку через час, пока обновление не пройдёт. Встроенные базы для записей <code>geosite:</code> и <code>geoip:</code> обновляются по тому же расписанию.

<b>Какие категории есть в файле</b>
Кнопка <b>категории</b> показывает список категорий каждого скачанного файла, с поиском по части названия. Запись block или WARP с категорией, которой в файле нет, бот не примет и назовёт причину.

<b>Шаг 3. Выбрать категорию и действие</b>
Если в sites.dat есть категория ads, добавьте в block:
<code>ext:sites.dat:ads</code>
Будут выбраны домены из этой категории.

Если в sites.dat есть категория video, можно добавить в WARP:
<code>ext:sites.dat:video</code>
Её домены пойдут через подключённый WARP, когда трафик поступит на сервер.

Если в networks.dat есть категория cdn, запись для IP:
<code>extip:networks.dat:cdn</code>
Её также можно добавить в block или WARP в зависимости от задачи.

<b>Чем отличаются ext: и extip:</b>
<code>ext:</code> выбирает доменную категорию;
<code>extip:</code> — категорию IP.
Имя файла должно совпадать с зарегистрированным, включая регистр. Категория должна реально существовать внутри файла; имена ads/video/cdn выше — условные примеры.

Один подключённый файл без ссылки на категорию ничего не блокирует. Если источник выключен и файл недоступен, правило не сможет использовать его содержимое.

Эти серверные файлы не передаются в клиентскую подписку. Для маршрутизации до сервера используйте подходящие клиентские правила.

<b>geosite: и geoip:</b>
Например, <code>geosite:google</code> или <code>geoip:de</code> ссылаются на категории баз Xray. Они требуют соответствующих геоданных там, где исполняется правило. Это не универсальная замена domain:/IP для всех клиентских форматов; состав категории зависит от базы.
