Регулярное выражение — шаблон для проверки <b>доменного имени</b>. Оно не просматривает содержимое сайта, адрес страницы, параметры ссылки или имя приложения.

<b>Разберём пример по частям</b>
<code>regexp:^ads[0-9]{1,3}\.example\.com$</code>
• <code>regexp:</code> — сообщает боту, что дальше шаблон.
• <code>^</code> — начало имени.
• <code>ads</code> — именно эти три буквы.
• <code>[0-9]</code> — одна цифра.
• <code>{1,3}</code> — предыдущий элемент повторяется от 1 до 3 раз.
• <code>\.</code> — обычная точка.
• <code>example\.com</code> — продолжение имени.
• <code>$</code> — конец имени.

✅ ads1.example.com, ads12.example.com, ads123.example.com
❌ ads.example.com, ads1234.example.com, xads1.example.com, ads1.example.com.net

<b>Полезные обозначения</b>
<code>.</code> — любой один символ, в том числе точка.
<code>\.</code> — только точка.
<code>*</code> — предыдущий элемент 0 или больше раз.
<code>+</code> — предыдущий элемент 1 или больше раз.
<code>?</code> — предыдущий элемент 0 или 1 раз.
<code>.*</code> — любая последовательность, даже пустая.
<code>[a-z]</code> — одна латинская строчная буква.
<code>[a-z0-9-]</code> — одна буква, цифра или дефис.
<code>[^.]</code> — один символ, кроме точки.
<code>{2}</code> — ровно два повторения.
<code>(api|cdn)</code> — api или cdn.
Скобки объединяют часть шаблона: <code>(www\.)?</code> означает необязательное www.

<b>Почему важны ^ и $</b>
Без ограничителей ищется совпавший фрагмент внутри имени. <code>regexp:example</code> найдёт и notexample.net. Чтобы проверить всё имя, используйте, например, <code>regexp:^example\.com$</code>.

Каждое выражение вводите отдельной строкой. В сообщении боту нужен один обратный слэш перед точкой: <code>\.</code>.
