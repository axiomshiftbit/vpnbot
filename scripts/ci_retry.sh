#!/bin/sh
# Повтор сетевой команды CI: до четырёх попыток с паузами 15, 45 и 90 с.
# Связь runner с GitHub, реестром образов и зеркалами пакетов иногда рвётся на
# минуту-две, и без повтора обрывался прогон, уже прошедший сборку или стенд.
# Код возврата — последней попытки. POSIX sh: скрипт вызывается и в Alpine.
set -u
# Отдельное слово в конце списка, а не нулевая пауза: «0» — допустимая пауза.
for delay in ${CI_RETRY_DELAYS:-15 45 90} last; do
    "$@" && exit 0
    code=$?
    [ "$delay" != last ] || exit "$code"
    echo "ci_retry: «$1» завершилась с кодом $code, повтор через $delay с" >&2
    sleep "$delay"
done
