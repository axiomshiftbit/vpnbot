#!/bin/sh
# OpenVPN Community Edition entrypoint.
# - Initializes easy-rsa PKI in /etc/openvpn/pki on first run.
# - Writes server.conf only if missing — bot edits port/isolation in place.
# - Runs sshd so the bot can `ssh ovpn ...` like every other container.
# - Starts openvpn in background; container stays alive via tail. Bot restarts
#   via `pkill openvpn; ssh ovpn 'openvpn --config ...'`.

set -e

cat /ssh/key.pub > /root/.ssh/authorized_keys
ssh-keygen -A
exec /usr/sbin/sshd -D -e "$@" &

INTERFACE=$(route | grep '^default' | grep -o '[^ ]*$')
PORT="${OVPNPORT:-1194}"
PROTO="${OVPNPROTO:-udp4}"
case "$PROTO" in udp4|tcp4) ;; *) PROTO="udp4" ;; esac
SUBNET="${OVPNSUBNET:-10.8.0.0/24}"
NET=$(echo "$SUBNET" | cut -d/ -f1)
MASK=$(echo "$SUBNET" | awk -F/ '{
    n=$2; for(i=0;i<4;i++){ b=(n>=8?8:n); printf("%s%d", i?".":"", 256-2^(8-b)); n-=b }
}')

PKI=/etc/openvpn/pki
SRV=/etc/openvpn/server.conf
EASYRSA_BIN=/usr/share/easy-rsa/easyrsa
export EASYRSA_PKI="$PKI"
export EASYRSA_BATCH=1

if [ ! -f "$PKI/ca.crt" ]; then
    rm -rf "$PKI"
    mkdir -p "$PKI"
    "$EASYRSA_BIN" init-pki
    "$EASYRSA_BIN" --req-cn="vpnbot-ovpn-ca" build-ca nopass
    "$EASYRSA_BIN" --req-cn="server" build-server-full server nopass
    "$EASYRSA_BIN" gen-crl
    openvpn --genkey secret "$PKI/ta.key"
fi

mkdir -p /etc/openvpn/ccd /etc/openvpn/clients

if [ ! -f "$SRV" ]; then
    cat > "$SRV" <<EOF
# Generated by vpnbot start_ovpn.sh — bot edits port/isolation in place.
port $PORT
proto $PROTO
dev tun
topology subnet

ca $PKI/ca.crt
cert $PKI/issued/server.crt
key $PKI/private/server.key
dh none
ecdh-curve prime256v1
tls-crypt $PKI/ta.key
crl-verify $PKI/crl.pem

cipher AES-256-GCM
auth SHA256
data-ciphers AES-256-GCM:AES-128-GCM:CHACHA20-POLY1305
data-ciphers-fallback AES-256-GCM
tls-version-min 1.2

server $NET $MASK
ifconfig-pool-persist /etc/openvpn/ipp.txt
push "redirect-gateway def1 bypass-dhcp"
push "dhcp-option DNS 10.10.0.5"
push "block-outside-dns"

client-config-dir /etc/openvpn/ccd
keepalive 10 60
explicit-exit-notify 1

# Bot toggles client isolation between these markers — do not edit by hand.
#ovpn-isolation
#ovpn-isolation

status /etc/openvpn/openvpn-status.log 5
status-version 2
log-append /logs/openvpn.log
verb 3

management 127.0.0.1 7505

persist-key
persist-tun
EOF
fi

iptables -t nat -A POSTROUTING -s "$SUBNET" -o "$INTERFACE" -j MASQUERADE 2>/dev/null || true

mkdir -p /dev/net
[ -c /dev/net/tun ] || mknod /dev/net/tun c 10 200

mkdir -p /logs
[ -f /logs/openvpn.log ] || : > /logs/openvpn.log

openvpn --config "$SRV" >/dev/null 2>&1 &

tail -f /dev/null
