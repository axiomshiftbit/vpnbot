"""DNS names must never turn domain routing into LAN access.

Run under unshare --net as root. Every address, DNS response and destination
belongs to this disposable namespace; no production LAN or DNS is contacted.
FREEDOM_RULES is generated by freedom-guard-profile.php from the actual bot.
"""
from collections import Counter
import copy
import ipaddress
import json
import os
from pathlib import Path
import shutil
import socket
import socketserver
import struct
import subprocess
import sys
import tempfile
import threading
import time
import uuid

if os.geteuid() != 0 or os.readlink('/proc/self/ns/net') == os.readlink('/proc/1/ns/net'):
    raise SystemExit('Disposable network namespace required')
os.umask(0o077)
sys.path.insert(0, str(Path(os.environ['NODE_SOURCE_DIR'])/'scripts'))
import node_config as node
cores = Path(os.environ['CORE_TEST_DIR'])
root = Path(tempfile.mkdtemp(prefix='node-dns-guard-', dir='/run'))
processes, servers = [], []
hits, queries = Counter(), Counter()
records, rebind = {}, False
checks = 0
PUBLIC = {4: '11.77.0.128', 6: '2620:fe::fe'}
OWN = {4: '11.77.0.4', 6: '2606:4700:4700::4'}
PRIVATE = ['10.10.0.15', '127.0.0.2', '192.168.77.1', '172.16.77.1',
           '100.64.0.2', '169.254.169.254', 'fd42:7662:99::1', '::1']
TCP_PORT, UDP_PORT = 18093, 18094


def check(label, ok):
    global checks
    print(('PASS ' if ok else 'FAIL ')+label, flush=True)
    if not ok:
        raise RuntimeError(label)
    checks += 1


def run(args, **kwargs):
    return subprocess.run(list(map(str, args)), capture_output=True, timeout=15, **kwargs)


class TCP(socketserver.BaseRequestHandler):
    def handle(self):
        self.request.settimeout(2)
        try:
            data = self.request.recv(128)
            if data == b'guard-probe':
                hits[self.server.server_address[0]] += 1
                self.request.sendall(data)
        except OSError:
            pass


class UDP(socketserver.BaseRequestHandler):
    def handle(self):
        data, sock = self.request
        hits[self.server.server_address[0]] += 1
        sock.sendto(data, self.client_address)


def fqdn(name):
    return b''.join(bytes([len(label)])+label.encode() for label in name.split('.'))+b'\0'


class DNS(socketserver.BaseRequestHandler):
    def handle(self):
        data, sock = self.request
        try:
            offset, labels = 12, []
            while data[offset]:
                length = data[offset]
                labels.append(data[offset+1:offset+1+length].decode().lower())
                offset += length+1
            offset += 1
            kind = struct.unpack('!H', data[offset:offset+2])[0]
            name = '.'.join(labels)
            queries[(name, kind)] += 1
            values = records.get(name, [])
            if name == 'rebind.guard.test':
                values = ['10.10.0.15', 'fd42:7662:99::1'] if rebind else list(PUBLIC.values())
            answers = []
            owner = b'\xc0\x0c'
            if name == 'cname.guard.test':
                target = fqdn('inner.guard.test')
                answers.append(owner+struct.pack('!HHIH', 5, 1, 0, len(target))+target)
                owner = target
                values = ['10.10.0.15', 'fd42:7662:99::1']
            for address in values:
                ip = ipaddress.ip_address(address)
                if kind != (1 if ip.version == 4 else 28):
                    continue
                packed = ip.packed
                answers.append(owner+struct.pack('!HHIH', kind, 1, 0, len(packed))+packed)
            question = data[12:offset+4]
            sock.sendto(data[:2]+b'\x81\x80'+struct.pack('!HHHH', 1, len(answers), 0, 0)
                        +question+b''.join(answers), self.client_address)
        except (IndexError, ValueError, UnicodeError, struct.error):
            pass


def listen(address, port, handler, udp=False):
    base = socketserver.ThreadingUDPServer if udp else socketserver.ThreadingTCPServer
    cls = type('Listener', (base,), {'address_family': socket.AF_INET6 if ':' in address else socket.AF_INET,
                                    'allow_reuse_address': True, 'daemon_threads': True})
    server = cls((address, port), handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    servers.append(server)


def target(address, port):
    try:
        ip = ipaddress.ip_address(address)
        return (b'\x01' if ip.version == 4 else b'\x04')+ip.packed+struct.pack('!H', port)
    except ValueError:
        raw = address.encode()
        return b'\x03'+bytes([len(raw)])+raw+struct.pack('!H', port)


def probe(address, udp=False, timeout=.45):
    try:
        with socket.create_connection(('127.0.0.1', 10875), timeout=1) as control:
            control.settimeout(timeout)
            control.sendall(b'\x05\x01\x00')
            if control.recv(2) != b'\x05\x00':
                return False
            if not udp:
                control.sendall(b'\x05\x01\x00'+target(address, TCP_PORT))
                answer = control.recv(256)
                if len(answer) < 2 or answer[1] != 0:
                    return False
                control.sendall(b'guard-probe')
                return control.recv(128) == b'guard-probe'
            control.sendall(b'\x05\x03\x00\x01'+b'\0'*6)
            answer = control.recv(256)
            if len(answer) < 10 or answer[1] != 0 or answer[3] != 1:
                return False
            port = struct.unpack('!H', answer[8:10])[0]
            with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
                sock.settimeout(timeout)
                sock.sendto(b'\0\0\0'+target(address, UDP_PORT)+b'guard-probe', ('127.0.0.1', port))
                return sock.recv(512).endswith(b'guard-probe')
    except OSError:
        return False


def start(binary, name, value):
    path = root/(name+'.json')
    path.write_text(json.dumps(value))
    check(name+' validates', run([binary, 'run', '-test', '-c', path]).returncode == 0)
    process = subprocess.Popen([str(binary), 'run', '-c', str(path)], stdout=subprocess.DEVNULL,
                               stderr=subprocess.DEVNULL, env=os.environ | {'GODEBUG': 'multipathtcp=0'})
    processes.append(process)
    time.sleep(.25)
    check(name+' runs', process.poll() is None)
    return process


def stop(process):
    process.terminate()
    process.wait(timeout=5)
    processes.remove(process)


try:
    run(['ip', 'link', 'set', 'lo', 'up'], check=True)
    for address in [*PUBLIC.values(), *OWN.values(), *PRIVATE, '11.77.0.2']:
        if address == '::1':
            continue
        run(['ip', 'addr', 'add', address+('/128' if ':' in address else '/32'), 'dev', 'lo'], check=True)
    for address in [*PUBLIC.values(), *OWN.values(), *PRIVATE]:
        listen(address, TCP_PORT, TCP)
        listen(address, UDP_PORT, UDP, True)
        with socket.create_connection((address, TCP_PORT), timeout=1) as conn:
            conn.sendall(b'guard-probe')
            check('target alive '+address, conn.recv(128) == b'guard-probe')
    listen('11.77.0.2', 53, DNS, True)
    listen(PUBLIC[6], 53, DNS, True)
    blocked = PRIVATE+list(OWN.values())
    for index, address in enumerate(blocked):
        name = address.replace('.', '-').replace(':', '-')+'.nip.io'
        records[name] = [address]
        records[f'private-{index}.sslip.io'] = [address]
    records['mapped.guard.test'] = ['::ffff:10.10.0.15']
    records['nat64.guard.test'] = ['64:ff9b::a0a:f']
    records['public.guard.test'] = list(PUBLIC.values())
    records['mixed.guard.test'] = list(PUBLIC.values())+['10.10.0.15', 'fd42:7662:99::1']
    names = [name for name in records if name not in ('public.guard.test', 'mixed.guard.test')]+['cname.guard.test']
    host = dict(public4=OWN[4], public6=OWN[6], sources=['11.77.0.3'], admins=['11.77.0.3'],
                routers=[], ssh_ports=[2222], interface='lo', uid=995, gid=995)
    keys = dict(uuid=str(uuid.uuid4()), private='A'*43, public='B'*43,
                short_id='a1b2c3d4a1b2c3d4', path='0123456789abcdef'*2)
    rules = json.loads(Path(os.environ['FREEDOM_RULES']).read_text())
    for core, binary in [('origin','x31'), ('fork','fork'), ('origin2','origin2'), ('origin3','origin3')]:
        for mode, family in [('node',4), ('node',6), ('main',4), ('main',6)]+([('legacy-control',4)] if core == 'origin' else []):
            label = f'{core}-{mode}-ipv{family}'
            options = dict(transport='reality', core=core, family=family, domain='', mask='mask.example.test')
            value = node.core_config(options, host, keys)
            # The real VLESS connection exercises Freedom's server-side policy.
            # TLS transports are covered separately; no external mask is used.
            value['inbounds'][0]['streamSettings'] = {'network':'tcp', 'security':'none'}
            value['inbounds'][0]['settings']['clients'][0].pop('flow', None)
            if mode != 'node':
                value['outbounds'][0]['settings']['finalRules'] = copy.deepcopy(rules)
                if mode == 'legacy-control':
                    value['outbounds'][0]['settings']['finalRules'] = [{'action':'allow','ip':['10.10.0.0/16']}, rules[-1]]
            value['outbounds'].append({'tag':'block','protocol':'blackhole'})
            value['routing'] = {'domainStrategy':'IPIfNonMatch','rules':[
                {'type':'field','domain':['domain:nip.io','domain:sslip.io','domain:guard.test'],'outboundTag':'direct'},
                {'type':'field','ip':['10.0.0.0/8','fc00::/7'],'outboundTag':'block'}]}
            value['dns'] = {'servers':['11.77.0.2' if family == 4 else PUBLIC[6]], 'queryStrategy':'UseIPv'+str(family), 'disableCache':True}
            server = start(cores/binary, label+'-server', value)
            client_value = {'log':{'loglevel':'none'}, 'inbounds':[{'listen':'127.0.0.1','port':10875,'protocol':'socks','settings':{'udp':True}}],
                'outbounds':[{'protocol':'vless','settings':{'address':'127.0.0.1','port':8443,'id':keys['uuid'],'encryption':'none'},
                              'streamSettings':{'network':'tcp','security':'none'}}]}
            client = start(cores/binary, label+'-client', client_value)
            for udp in (False, True):
                suffix = ' UDP' if udp else ' TCP'
                check(label+' public DNS positive control'+suffix, probe('public.guard.test', udp, timeout=3))
                if mode == 'legacy-control':
                    check(label+' reproduces old domain routing bypass'+suffix, probe('10-10-0-15.nip.io', udp, timeout=3))
                    continue
                before = sum(hits[address] for address in blocked)
                for name in names:
                    # Own IPv6 is not blocked by the old full-bot finalRules;
                    # host origin guards are tested independently.
                    if mode == 'main' and records.get(name, [None])[0] in OWN.values():
                        continue
                    check(label+' denies '+name+suffix, not probe(name, udp))
                rebind = False
                check(label+' rebinding public phase'+suffix, probe('rebind.guard.test', udp, timeout=3))
                rebind = True
                count = queries[('rebind.guard.test', 1 if family == 4 else 28)]
                for _ in range(4):
                    check(label+' rebinding private phase'+suffix, not probe('rebind.guard.test', udp))
                check(label+' DNS was refreshed'+suffix, queries[('rebind.guard.test', 1 if family == 4 else 28)] > count)
                probe('mixed.guard.test', udp)
                check(label+' no private destination received data'+suffix, sum(hits[address] for address in blocked) == before)
            stop(client)
            stop(server)
    print(f'PASS {checks} DNS isolation checks', flush=True)
finally:
    for process in processes:
        process.terminate()
        process.wait(timeout=5)
    for server in servers:
        server.shutdown()
        server.server_close()
    shutil.rmtree(root)
