<?php

// TrustTunnel + OpenVPN: инварианты, которые ловятся не предупреждением, а
// отказом клиента подключиться.
//
// TrustTunnel (CONFIGURATION.md + lib/src/client_config.rs апстрима):
//  1. credentials.toml — последовательность [[client]] с username/password;
//     сырые управляющие символы в TOML-строке недопустимы, один \n в пароле
//     ломает разбор всего файла и эндпоинт не стартует;
//  2. клиентский конфиг ПЛОСКИЙ (compose_toml() пишет ключи в корень
//     документа) — секции [endpoint] в нём нет;
//  3. self-signed сертификат обязан попасть в поле certificate, иначе клиент
//     отвергает TLS-цепочку.
//
// OpenVPN:
//  4. блокировка клиента = директива `disable` отдельной строкой в ccd/<CN>,
//     а не любое вхождение подстроки;
//  5. block-outside-dns разбирается только под #ifdef _WIN32 (options.c), в
//     PUSH_REPLY для не-Windows клиента это фатальная ошибка — переключатель
//     обязан по умолчанию оставлять блок между маркерами пустым;
//  6. status-version 2: CLIENT_LIST,CN,Real,Virtual,VirtualIPv6,rx,tx,since,
//     since_t,Username,ClientID,... (src/openvpn/multi.c).

require_once __DIR__ . '/../app/bot.php';

$failed = 0;

function ttAssert(bool $cond, string $msg): void
{
    global $failed;
    if (!$cond) {
        $failed++;
        echo "FAIL: $msg\n";
    }
}

$bot = (new ReflectionClass(Bot::class))->newInstanceWithoutConstructor();

// Подставляем окружение вместо файлов на диске: pac.json, домен и порт — всё,
// от чего зависят сборщики конфигов.
$stub = new class extends Bot {
    public $pacStub  = ['domain' => 'vpn.example.com', 'letsencrypt' => 'letsencrypt'];
    public $certStub = '';
    public function __construct() {}
    public function getPacConf(): array
    {
        return $this->pacStub;
    }
    public function ttDomain()
    {
        return $this->pacStub['domain'];
    }
    public function getTtPort()
    {
        return 2443;
    }
};

// ── 1. credentials.toml: запись → чтение ────────────────────────────────────
$dir = sys_get_temp_dir() . '/tt_ovpn_test_' . getmypid();
@mkdir($dir . '/config/trusttunnel', 0755, true);

// ttPaths() прибит к /config/trusttunnel, поэтому проверяем сам формат:
// генерируем блоки той же функцией-склейкой и разбираем тем же regexp.
$emit = function (array $users): string {
    $out = "# TrustTunnel credentials. Generated by bot — do not edit manually.\n";
    foreach ($users as $u => $p) {
        $out .= "\n[[client]]\nusername = \"" . addcslashes($u, '"\\') . "\"\n"
             .  "password = \"" . addcslashes($p, '"\\') . "\"\n";
    }
    return $out;
};
$parse = function (string $data): array {
    $users = [];
    foreach (preg_split('~^[ \t]*\[\[client\]\][ \t]*$~m', $data) as $block) {
        if (!preg_match('~^[ \t]*username[ \t]*=[ \t]*"((?:[^"\\\\]|\\\\.)*)"~m', $block, $u)) {
            continue;
        }
        if (!preg_match('~^[ \t]*password[ \t]*=[ \t]*"((?:[^"\\\\]|\\\\.)*)"~m', $block, $pw)) {
            continue;
        }
        $users[stripcslashes($u[1])] = stripcslashes($pw[1]);
    }
    return $users;
};

$users = ['alice' => 'p@ss', 'bob' => 'quote"and\\slash'];
ttAssert($parse($emit($users)) === $users, 'credentials.toml: кавычки и слэши переживают round-trip');

// Блок без password не должен «занять» пароль следующего клиента.
$broken = "[[client]]\nusername = \"ghost\"\n\n[[client]]\nusername = \"real\"\npassword = \"secret\"\n";
$got    = $parse($broken);
ttAssert(!isset($got['ghost']), 'клиент без password игнорируется, а не крадёт чужой');
ttAssert(($got['real'] ?? '') === 'secret', 'следующий за битым блоком клиент разбирается верно');

// ── 1b. backup → restore: реальный round-trip через методы бота ────────────
// Восстановление кладёт credentials.toml из снимка СЫРЫМ, после чего
// restartTt() перечитывает его getClientsTt() и перезаписывает
// writeTtCredentials(). Любая потеря на этом круге = у клиента отняли доступ.
$ttDir = $dir . '/config/trusttunnel';
$ttBox = new class ($ttDir) extends Bot {
    private $d;
    public function __construct($d)
    {
        $this->d = $d;
    }
    public function ttPaths()
    {
        return [
            'dir'   => $this->d,
            'vpn'   => $this->d . '/vpn.toml',
            'hosts' => $this->d . '/hosts.toml',
            'cred'  => $this->d . '/credentials.toml',
            'rules' => $this->d . '/rules.toml',
            'log'   => $this->d . '/log',
        ];
    }
};

$backup = [
    'short'     => 'p@ss',
    'generated' => base64_encode(random_bytes(18)),
    'long'      => str_repeat('L', 200),               // длиннее прежнего лимита 128
    'quoted'    => 'a"b\\c',
    'unicode'   => 'пароль-Ω-1',
    'spaces'    => 'two words here',
];
$ttBox->writeTtCredentials($backup);
$snapshot = file_get_contents($ttDir . '/credentials.toml');   // это и есть $json['tt']

// restore: файл кладётся как есть, затем restartTt() читает и перезаписывает.
file_put_contents($ttDir . '/credentials.toml', $snapshot);
$afterRestore = $ttBox->getClientsTt();
ttAssert($afterRestore === $backup, 'restore бэкапа не теряет и не искажает клиентов TT');
$ttBox->writeTtCredentials($afterRestore);
ttAssert($ttBox->getClientsTt() === $backup, 'повторная перезапись идемпотентна');
ttAssert(
    strlen($afterRestore['long']) === 200,
    'длинный пароль из бэкапа не обрезается при перезаписи (иначе клиент теряет доступ)'
);

// Файл, записанный СТАРОЙ версией бота (тот же addcslashes), обязан читаться.
$legacy = "# TrustTunnel credentials. Generated by bot — do not edit manually.\n"
    . "\n[[client]]\nusername = \"old\"\npassword = \"" . addcslashes('a"b\\c', '"\\') . "\"\n";
file_put_contents($ttDir . '/credentials.toml', $legacy);
ttAssert($ttBox->getClientsTt() === ['old' => 'a"b\\c'], 'credentials.toml от старой версии читается без потерь');

// ── 2. санитайзер пароля ────────────────────────────────────────────────────
$sanitize = fn($s, $max = 128) => mb_substr(trim(preg_replace('~[\x00-\x1F\x7F]~', '', (string) $s)), 0, $max);
ttAssert($bot->ttSanitize(str_repeat('x', 300)) === str_repeat('x', 300), 'ttSanitize без лимита не режет длину');
ttAssert(mb_strlen($bot->ttSanitize(str_repeat('x', 300), 128)) === 128, 'ttSanitize с лимитом режет');
ttAssert($bot->ttSanitize("pa\nss") === 'pass', 'ttSanitize вычищает управляющие символы всегда');
ttAssert(strpos($sanitize("pa\nss"), "\n") === false, 'перевод строки вырезается из пароля');
ttAssert($sanitize("pa\x00ss") === 'pass', 'NUL вырезается из пароля');
ttAssert($sanitize('') === '', 'пустой пароль остаётся пустым (вызывающий обязан отбраковать)');
ttAssert(mb_strlen($sanitize(str_repeat('x', 500))) === 128, 'длина пароля ограничена');
// Санитайзер обязан быть достаточным: результат не должен содержать ничего,
// что ломает TOML-строку после addcslashes.
$hard = addcslashes($sanitize("a\"b\\c\r\nd"), '"\\');
ttAssert(preg_match('~^[^"\\\\\x00-\x1F]*(\\\\.[^"\\\\\x00-\x1F]*)*$~', $hard) === 1, 'экранированная строка валидна для TOML');

// ── 3. клиентский конфиг: плоский формат + сертификат ───────────────────────
$cert = "-----BEGIN CERTIFICATE-----\nMIIB\n-----END CERTIFICATE-----";
$mkPacFallback = function (string $le, string $certPem) {
    // Повторяем ветвление ttFallbackConfig() без обращения к /certs.
    $inc = ($le !== 'letsencrypt') && $certPem !== '';
    return $inc
        ? "certificate = \"\"\"\n$certPem\n\"\"\"\n"
        : "certificate = \"\"\n";
};
ttAssert(
    strpos($mkPacFallback('self', $cert), 'BEGIN CERTIFICATE') !== false,
    'self-signed сертификат попадает в клиентский конфиг'
);
ttAssert(
    strpos($mkPacFallback('letsencrypt', $cert), 'BEGIN CERTIFICATE') === false,
    'для Let\'s Encrypt поле certificate остаётся пустым (проверка системными CA)'
);

$sample = $stub->ttFallbackConfig('alice', 'p@ss');
ttAssert(strpos($sample, '[endpoint]') === false, 'в клиентском конфиге НЕТ секции [endpoint]');
foreach (['hostname', 'addresses', 'username', 'password', 'upstream_protocol', 'has_ipv6', 'anti_dpi'] as $k) {
    ttAssert((bool) preg_match("~^$k\\s*=~m", $sample), "клиентский конфиг содержит ключ $k в корне");
}

// deeplink вытаскивается из вывода бинаря, где после ссылки идёт подсказка.
$out = "tt://?AQ9leGFtcGxl\n\nTo connect on mobile, you can scan QR code on the page: https://x/#tt=AQ\n";
ttAssert(
    preg_match('~tt://\S+~', $out, $m) && $m[0] === 'tt://?AQ9leGFtcGxl',
    'deep link отделяется от подсказки бинаря'
);

// ── 4. ccd: `disable` только отдельной строкой ──────────────────────────────
$isDisabled = fn($body) => (bool) preg_match('~^[ \t]*disable[ \t]*$~m', $body);
ttAssert($isDisabled("disable\n"), 'директива disable распознаётся');
ttAssert($isDisabled("ifconfig-push 10.8.0.5 255.255.255.0\ndisable\n"), 'disable среди других директив');
ttAssert(!$isDisabled("# disabled by admin\n"), 'комментарий про disabled не блокирует клиента');
ttAssert(!$isDisabled("push \"route 10.0.0.0 255.0.0.0\" # disable later\n"), 'подстрока в другой директиве не считается');

// ── 5. block-outside-dns: маркеры и переключатель ───────────────────────────
$re      = '~^[ \t]*#ovpn-winblockdns[ \t]*\R(.*?)^[ \t]*#ovpn-winblockdns[ \t]*$~sm';
$emptyBl = "port 1194\n\n#ovpn-winblockdns\n#ovpn-winblockdns\n\nverb 3\n";
ttAssert(preg_match($re, $emptyBl, $m) === 1, 'пустой блок маркеров матчится (.*?, не .+?)');
ttAssert(!preg_match('~^\s*push\s+"block-outside-dns"~m', $m[1]), 'по умолчанию push выключен');

$onBl = preg_replace($re, "#ovpn-winblockdns\npush \"block-outside-dns\"\n#ovpn-winblockdns", $emptyBl);
ttAssert(preg_match($re, $onBl, $m2) === 1 && preg_match('~^\s*push\s+"block-outside-dns"~m', $m2[1]), 'включение пишет push внутрь блока');
$offBl = preg_replace($re, "#ovpn-winblockdns\n#ovpn-winblockdns", $onBl);
ttAssert(strpos($offBl, 'block-outside-dns"') === false, 'выключение убирает push целиком');
ttAssert(strpos($offBl, 'verb 3') !== false && strpos($offBl, 'port 1194') !== false, 'переключение не съедает остальной конфиг');

// Миграции обязаны жить в отдельном скрипте: их гоняет и стартовый скрипт
// контейнера, и бот перед каждым стартом демона. Иначе восстановление из
// бэкапа (importOvpnPki кладёт server.conf из снимка целиком) молча
// откатывает их — ровно это и случилось на живом сервере.
$mig = file_get_contents(__DIR__ . '/../scripts/ovpn_migrate.sh');
ttAssert(strpos($mig, '#ovpn-winblockdns') !== false, 'ovpn_migrate.sh заводит маркеры winblockdns');
ttAssert(
    strpos($mig, "sed -i '/^[[:space:]]*push[[:space:]]\\+\"block-outside-dns\"/d'") !== false,
    'ovpn_migrate.sh снимает безусловный push "block-outside-dns"'
);
ttAssert(strpos($mig, 'persist-key') !== false, 'ovpn_migrate.sh убирает deprecated persist-key');
$startOvpn = file_get_contents(__DIR__ . '/../scripts/start_ovpn.sh');
ttAssert(strpos($startOvpn, 'sh /ovpn_migrate.sh') !== false, 'start_ovpn.sh зовёт общий скрипт миграций');
$botSrc = file_get_contents(__DIR__ . '/../app/bot.php');
ttAssert(
    strpos($botSrc, 'sh /ovpn_migrate.sh') !== false,
    'бот применяет миграции сам (иначе restore бэкапа откатывает их)'
);
ttAssert(
    (bool) preg_match('~function restartOvpn\(\)\s*\{\s*\$this->migrateOvpnServerConf\(\);~', $botSrc),
    'restartOvpn() применяет миграции до старта демона'
);
ttAssert(
    strpos($botSrc, 'nobind\\npersist-tun\\nremote-cert-tls server') !== false,
    'клиентский .ovpn без deprecated persist-key'
);

// TrustTunnel: эндпоинт паникует на credentials.toml без [[client]]
// («invalid value: Not an array of clients») — стартовый скрипт обязан
// гейтить это так же, как ttBlockers() в боте.
$startTt = file_get_contents(__DIR__ . '/../scripts/start_tt.sh');
ttAssert(strpos($startTt, '[[client]]') !== false, 'start_tt.sh проверяет наличие [[client]]');
ttAssert(strpos($startTt, 'cert_private') !== false, 'start_tt.sh проверяет наличие сертификатов');

// Генерируемый server.conf не должен пушить опцию безусловно.
$srv = file_get_contents(__DIR__ . '/../scripts/start_ovpn.sh');
ttAssert(
    !preg_match('~^push "block-outside-dns"~m', $srv),
    'start_ovpn.sh не пишет push "block-outside-dns" в шаблон server.conf'
);
ttAssert(strpos($srv, '#ovpn-winblockdns') !== false, 'start_ovpn.sh раскладывает маркеры переключателя');
ttAssert(
    !preg_match('~^cipher [A-Z]~m', $srv),
    'start_ovpn.sh не пишет deprecated-директиву cipher в TLS-режиме'
);

// ── 5b. PKI-транзакции: add/delete/backup/restore/start ────────────────────
foreach (['exportOvpnPki', 'importOvpnPki'] as $fn) {
    $body = substr($botSrc, strpos($botSrc, "public function $fn("), 1500);
    ttAssert(strpos($body, 'withOvpnPkiLock(') !== false, "$fn выполняется под общим PKI-lock");
}
$addBody = substr($botSrc, strpos($botSrc, 'public function addovus('), 5000);
$delBody = substr($botSrc, strpos($botSrc, 'public function delOvpnUser('), 6000);
ttAssert(strpos($addBody, 'withOvpnPkiLock(') !== false, 'выдача OpenVPN-сертификата выполняется под PKI-lock');
ttAssert(strpos($delBody, 'withOvpnPkiLock(') !== false, 'отзыв OpenVPN-сертификата выполняется под PKI-lock');
ttAssert(strpos($delBody, '__VPNBOT_REVOKED__') !== false && strpos($delBody, 'Serial Number: \$serial') !== false,
    'успех revoke подтверждается наличием serial в новом CRL');
ttAssert(strpos($delBody, '>>/logs/openvpn.log 2>&1') !== false,
    'ошибка revoke действительно попадает в журнал из сообщения бота');
ttAssert(strpos($startOvpn, 'exec 8>/logs/.lock.ovpn-pki') !== false,
    'start_ovpn.sh использует тот же lock-файл, что php');
ttAssert(strpos($startOvpn, 'flock 8') < strpos($startOvpn, 'gen-crl'),
    'start_ovpn.sh берёт PKI-lock до gen-crl');
ttAssert(strpos($startOvpn, 'flock -u 8') > strpos($startOvpn, 'sh /ovpn_migrate.sh'),
    'start_ovpn.sh отпускает PKI-lock только после всех изменений');

// ── 6. status-version 2: порядок колонок ────────────────────────────────────
$row  = 'CLIENT_LIST,alice,203.0.113.7:51820,10.8.0.2,,1024,2048,2026-08-02 10:00:00,1785600000,UNDEF,3,4,AES-256-GCM';
// $escape задаём явно: в PHP 8.4 вызов без него — deprecated, а с 9.0 значение
// по умолчанию меняется на "" (сейчас "\"). OpenVPN status-version 2 экранирования
// не использует, поэтому пустая строка — то же поведение, но зафиксированное.
$cols = str_getcsv($row, ',', '"', '');
ttAssert($cols[1] === 'alice', 'колонка 1 — Common Name');
ttAssert($cols[2] === '203.0.113.7:51820', 'колонка 2 — Real Address');
ttAssert($cols[3] === '10.8.0.2', 'колонка 3 — Virtual Address');
ttAssert((int) $cols[5] === 1024 && (int) $cols[6] === 2048, 'колонки 5/6 — принято/отдано');
ttAssert($cols[7] === '2026-08-02 10:00:00', 'колонка 7 — Connected Since');

ttAssert($bot->ovpnRealIp('203.0.113.7:51820') === '203.0.113.7', 'IPv4:port обрезается до адреса');
ttAssert($bot->ovpnRealIp('[2001:db8::1]:443') === '2001:db8::1', 'IPv6 в скобках обрезается');
ttAssert($bot->ovpnRealIp('2001:db8::1') === '2001:db8::1', 'голый IPv6 не калечится');
ttAssert($bot->ovpnIpIsProxied('10.10.0.10'), 'адрес docker-сети распознан как проксированный');
ttAssert(!$bot->ovpnIpIsProxied('203.0.113.7'), 'публичный адрес не считается проксированным');

// ── 7. vpn.toml: имена ключей строго по CONFIGURATION.md ────────────────────
$vpn = file_get_contents(__DIR__ . '/../config/trusttunnel/vpn.toml');
foreach (['recv_udp_payload_size', 'send_udp_payload_size', 'enable_early_data'] as $k) {
    ttAssert(strpos($vpn, $k) !== false, "vpn.toml использует официальное имя $k");
}
foreach (['udp_payload_size = ', 'early_data = '] as $k) {
    ttAssert(strpos($vpn, "\n$k") === false, "vpn.toml не содержит несуществующего ключа $k");
}
ttAssert(preg_match('~^listen_address = "0\.0\.0\.0:8443"~m', $vpn) === 1, 'listen_address совпадает с портом контейнера');

foreach (glob($dir . '/config/trusttunnel/*') ?: [] as $f) {
    @unlink($f);
}
@rmdir($dir . '/config/trusttunnel');
@rmdir($dir . '/config');
@rmdir($dir);

if ($failed) {
    echo "$failed test(s) failed\n";
    exit(1);
}
echo "tt/ovpn: all checks passed\n";
